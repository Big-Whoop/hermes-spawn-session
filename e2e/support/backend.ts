// Backend under test: an isolated `hermes serve` plus a mock LLM provider.
//
// Two modes:
// - Local (default): global setup creates a sandbox HERMES_HOME, links this repo
//   in as plugins/spawn-session, writes a config.yaml pointing at the mock LLM,
//   and starts `hermes serve --port <free>` with a known session token.
// - External: HERMES_DESKTOP_REMOTE_URL + HERMES_DESKTOP_REMOTE_TOKEN point at a
//   backend someone else started (the hermes-staging Job). E2E_HERMES_HOME must
//   then name that backend's HERMES_HOME so specs can seed parent sessions, and
//   E2E_MOCK_LLM_URL the mock provider it uses (optional; scripted-turn specs
//   skip without it).
//
// Global setup writes the resolved values to a state file so every spec
// (separate worker processes) reads the same backend.
import { spawn, spawnSync, type ChildProcess } from 'node:child_process'
import { randomBytes } from 'node:crypto'
import * as fs from 'node:fs'
import * as net from 'node:net'
import * as os from 'node:os'
import * as path from 'node:path'
import { fileURLToPath } from 'node:url'

import { MOCK_MODEL } from './mock-llm.js'

export const E2E_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
export const REPO_ROOT = path.resolve(E2E_DIR, '..')
// Global setup picks the path and exports it via E2E_STATE_FILE; Playwright
// passes env changes made in global setup on to the workers.
export const STATE_FILE = path.join(os.tmpdir(), `spawn-session-e2e-state-${process.pid}.json`)
export const PLUGIN = 'spawn-session'
export const API = `/api/plugins/${PLUGIN}`

export const HERMES_BIN = process.env.HERMES_BIN || 'hermes'
// Python of the Hermes install (used to seed sessions with the in-process gateway).
export const HERMES_PYTHON = process.env.HERMES_PYTHON || 'python3'

export interface BackendState {
  url: string
  token: string
  hermesHome: string
  /** Project dir that seeded parent sessions use as cwd. */
  projectDir: string
  mockLlmUrl: string | null
  /** True when global setup started (and must stop) the backend. */
  owned: boolean
  pid: number | null
  logFile: string | null
  sandboxRoot: string | null
}

export function readState(): BackendState {
  return JSON.parse(fs.readFileSync(stateFilePath(), 'utf8')) as BackendState
}

export function stateFilePath(): string {
  return process.env.E2E_STATE_FILE || STATE_FILE
}

export function writeState(state: BackendState): void {
  fs.writeFileSync(stateFilePath(), JSON.stringify(state, null, 2), { mode: 0o600 })
}

export async function freePort(): Promise<number> {
  return new Promise((resolve, reject) => {
    const s = net.createServer()
    s.on('error', reject)
    s.listen(0, '127.0.0.1', () => {
      const { port } = s.address() as net.AddressInfo
      s.close(() => resolve(port))
    })
  })
}

/** config.yaml for the sandbox: mock provider, plugin enabled, report injection allowed. */
export function configYaml(mockLlmUrl: string): string {
  return [
    '# Auto-generated by spawn-session e2e global setup',
    'model:',
    `  default: ${MOCK_MODEL}`,
    '  provider: custom',
    `  base_url: ${mockLlmUrl}`,
    '  api_key: e2e-no-key',
    '  context_length: 64000',
    'auxiliary:',
    '  title_generation:',
    '    enabled: false',
    'approvals:',
    '  mode: "off"',
    'onboarding:',
    '  run: false',
    'plugins:',
    '  enabled:',
    `    - ${PLUGIN}`,
    '  entries:',
    `    ${PLUGIN}:`,
    '      allow_gateway_injection: true',
    // D6 cost rule (AT2.3): the parent's mock model is cheap, the "pricey"
    // mock model is more expensive, so a spawn with it becomes a proposal.
    '      cost_rank:',
    `        "custom:${MOCK_MODEL}": 1`,
    `        "custom:${MOCK_MODEL}-pricey": 5`,
    ''
  ].join('\n')
}

/** git init + one commit + a bare `origin` remote (idempotent for an existing repo). */
export function initProjectRepo(projectDir: string, remoteDir: string): void {
  const git = (cwd: string, ...args: string[]) => {
    const r = spawnSync('git', ['-C', cwd, ...args], {
      encoding: 'utf8',
      env: { ...process.env, GIT_AUTHOR_NAME: 'e2e', GIT_AUTHOR_EMAIL: 'e2e@localhost', GIT_COMMITTER_NAME: 'e2e', GIT_COMMITTER_EMAIL: 'e2e@localhost' }
    })
    if (r.status !== 0) throw new Error(`git ${args.join(' ')} failed in ${cwd}: ${r.stderr}`)
    return r.stdout.trim()
  }
  if (!fs.existsSync(path.join(projectDir, '.git'))) git(projectDir, 'init', '-q', '-b', 'main')
  if (spawnSync('git', ['-C', projectDir, 'rev-parse', '--verify', '-q', 'HEAD']).status !== 0) {
    // Handovers live under .hermes/ in the project; keep them out of worktrees.
    fs.writeFileSync(path.join(projectDir, '.gitignore'), '.hermes/\n.worktrees/\n')
    fs.writeFileSync(path.join(projectDir, 'README.md'), '# e2e project\n')
    git(projectDir, 'add', '.gitignore', 'README.md')
    git(projectDir, 'commit', '-q', '-m', 'e2e: initial commit')
  }
  if (!git(projectDir, 'remote').split('\n').includes('origin')) {
    fs.mkdirSync(remoteDir, { recursive: true })
    git(remoteDir, 'init', '-q', '--bare')
    git(projectDir, 'remote', 'add', 'origin', remoteDir)
  }
}

/** Environment for the backend: strip HERMES_* and credentials (as upstream remote-helpers.ts). */
export function cleanEnv(): Record<string, string> {
  const env: Record<string, string> = {}
  for (const [k, v] of Object.entries(process.env)) {
    if (v && !/^_?HERMES_/.test(k) && !/(_API_KEY|_TOKEN|_SECRET|_PASSWORD|_BASE_URL)$/.test(k) && k !== 'VIRTUAL_ENV') env[k] = v
  }
  return env
}

export async function waitReady(url: string, token: string, child: ChildProcess | null, timeoutMs = 90_000): Promise<void> {
  const end = Date.now() + timeoutMs
  let last = ''
  while (Date.now() < end) {
    if (child && child.exitCode !== null) throw new Error(`hermes serve exited early (code ${child.exitCode})`)
    try {
      const res = await fetch(`${url}${API}/tree`, { headers: { Authorization: `Bearer ${token}` } })
      if (res.ok) return
      last = `HTTP ${res.status}`
    } catch (err) {
      last = String(err)
    }
    await new Promise(r => setTimeout(r, 500))
  }
  throw new Error(`backend not ready at ${url} after ${timeoutMs} ms (${last})`)
}

export interface StartedBackend {
  state: BackendState
  child: ChildProcess
}

export async function startLocalBackend(mockLlmUrl: string): Promise<StartedBackend> {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'spawn-session-e2e-'))
  const home = path.join(root, 'home')
  const hermesHome = path.join(root, 'hermes-home')
  const projectDir = path.join(root, 'project')
  for (const d of [home, hermesHome, path.join(hermesHome, 'plugins'), projectDir]) fs.mkdirSync(d, { recursive: true })
  fs.symlinkSync(REPO_ROOT, path.join(hermesHome, 'plugins', PLUGIN))
  fs.writeFileSync(path.join(hermesHome, 'config.yaml'), configYaml(mockLlmUrl))
  // A git repo with one commit and a bare `origin` as project: handovers are
  // written under <cwd>/.hermes/handovers, and worktree specs (AT2.5/AT7.2)
  // branch off it and push WIP commits to the remote.
  initProjectRepo(projectDir, path.join(root, 'origin.git'))

  const port = await freePort()
  const token = randomBytes(24).toString('base64url')
  const url = `http://127.0.0.1:${port}`
  const logFile = path.join(root, 'serve.log')
  const out = fs.openSync(logFile, 'a')
  const child = spawn(HERMES_BIN, ['serve', '--host', '127.0.0.1', '--port', String(port), '--skip-build'], {
    cwd: root,
    env: { ...cleanEnv(), HOME: home, HERMES_HOME: hermesHome, HERMES_DASHBOARD_SESSION_TOKEN: token },
    stdio: ['ignore', out, out],
    detached: true
  })
  child.unref()
  child.on('exit', (code, signal) => {
    // Teardown may already have removed the sandbox; the log line is best-effort.
    try {
      fs.appendFileSync(logFile, `\n[e2e] hermes serve exited code=${code} signal=${signal}\n`)
    } catch {}
  })
  await waitReady(url, token, child)
  return {
    child,
    state: { url, token, hermesHome, projectDir, mockLlmUrl, owned: true, pid: child.pid ?? null, logFile, sandboxRoot: root }
  }
}

export function externalBackend(): BackendState | null {
  const url = process.env.HERMES_DESKTOP_REMOTE_URL
  const token = process.env.HERMES_DESKTOP_REMOTE_TOKEN
  if (!url || !token) return null
  const hermesHome = process.env.E2E_HERMES_HOME
  if (!hermesHome) throw new Error('external backend mode needs E2E_HERMES_HOME (the backend\'s HERMES_HOME) to seed sessions')
  const projectDir = process.env.E2E_PROJECT_DIR || fs.mkdtempSync(path.join(os.tmpdir(), 'spawn-session-e2e-project-'))
  initProjectRepo(projectDir, `${projectDir}.origin.git`)
  return {
    url: url.replace(/\/$/, ''), token, hermesHome, projectDir,
    mockLlmUrl: process.env.E2E_MOCK_LLM_URL || null,
    owned: false, pid: null, logFile: null, sandboxRoot: null
  }
}

/** Log files of the backend's HERMES_HOME (agent.log, errors.log, gui.log). */
export function readLogs(state: BackendState): string {
  const dir = path.join(state.hermesHome, 'logs')
  if (!fs.existsSync(dir)) return ''
  return fs.readdirSync(dir).filter(f => f.endsWith('.log'))
    .map(f => fs.readFileSync(path.join(dir, f), 'utf8')).join('\n')
}
